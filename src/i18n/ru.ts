/*
 * Two features of Russian shape the phrasing here more than any single word does.
 *
 * A noun agrees with the number in front of it — 1 игрок, 3 игрока, 5 игроков — so a
 * count that arrives without a plural key of its own is put after a colon ("игроков:
 * 12"), which reads correctly for every number, rather than in front of a noun that
 * would be wrong for 21, 31 and 41.
 *
 * And a past-tense verb agrees with the gender of its subject, which a name does not
 * reveal. So a toast about a person leans on "игрок" for the agreement ("Игрок Анна
 * добавлен" is grammatical), and one about a level, whose name is whatever the manager
 * typed, takes the impersonal "Добавлено: …".
 */
